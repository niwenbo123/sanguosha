def init_preset_data():
    from app import db
    from app.models import Skill, Hero, Card, Equipment, Marker, GameState

    if Skill.query.count() == 0:
        for skill_data in SKILLS_DATA:
            skill = Skill(
                name=skill_data['name'],
                description=skill_data['description'],
                skill_type=skill_data['skill_type'],
                can_transform=skill_data['can_transform']
            )
            db.session.add(skill)
        db.session.commit()

    if Hero.query.count() == 0:
        for hero_data in HEROES_DATA:
            hero = Hero(
                name=hero_data['name'],
                camp=hero_data['camp'],
                hp=hero_data['hp']
            )
            for skill_name in hero_data['skills']:
                skill = Skill.query.filter_by(name=skill_name).first()
                if skill:
                    hero.skills.append(skill)
            db.session.add(hero)
        db.session.commit()

    if Card.query.count() == 0:
        for card_data in CARDS_DATA:
            card = Card(
                name=card_data['name'],
                card_type=card_data['card_type'],
                description=card_data['description']
            )
            db.session.add(card)
        db.session.commit()

